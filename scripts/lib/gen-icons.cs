// Icon generator for scripts/gen-icons.sh (a .NET file-based app; run it through that script).
//
// Reads the master SVGs in assets/icon and writes every platform icon asset under <out root>, which is the
// repository root (or a scratch directory that mirrors it, for --check). Output is text only (vector
// drawables, SVG, JSON) and byte-for-byte deterministic: same masters, same files.
//
//   mark.svg + background.svg -> src/PenBridge.Android/Resources/drawable/ic_launcher_{foreground,background,monochrome}.xml
//                                src/PenBridge.Android/Resources/mipmap-anydpi-v26/ic_launcher{,_round}.xml
//                                src/PenBridge.Mac/Resources/AppIcon.icon (Icon Composer: icon.json + one SVG per layer)
//   menubar-<state>.svg       -> src/PenBridge.Mac/Resources/Assets.xcassets/MenuBar<State>.imageset (template, vector)
//
// The SVG -> VectorDrawable conversion supports exactly the subset documented in mark.svg and fails on anything
// else, so a master can't silently lose a feature on Android.
//
// Usage: dotnet run --file scripts/lib/gen-icons.cs -- <assets/icon dir> <out root>
// Exit code 0 = written, 1 = a master is invalid, 2 = usage error.
#pragma warning disable CA1303 // CLI output strings are not localized.

using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: gen-icons.cs <assets/icon dir> <out root>");
    return 2;
}

string src = Path.GetFullPath(args[0]);
string root = Path.GetFullPath(args[1]);
try
{
    Generator.Run(src, root);
    return 0;
}
catch (InvalidDataException ex)
{
    Console.Error.WriteLine("gen-icons: " + ex.Message);
    return 1;
}

static class Generator
{
    static readonly XNamespace Svg = "http://www.w3.org/2000/svg";
    const string AndroidNs = "http://schemas.android.com/apk/res/android";
    const string AaptNs = "http://schemas.android.com/aapt";
    const string AndroidRes = "src/PenBridge.Android/Resources";
    const string MacRes = "src/PenBridge.Mac/Resources";

    // Menu-bar states, in the order StatusItemController maps them.
    static readonly (string State, string Asset)[] MenuBarStates =
    [
        ("idle", "MenuBarIdle"),
        ("connected", "MenuBarConnected"),
        ("paused", "MenuBarPaused"),
        ("attention", "MenuBarAttention"),
    ];

    // The macOS icon crops mark.svg to this square (1024-unit canvas): the concept's tile showed the mark at
    // 1.08x inside an 824-unit tile, i.e. 512 +/- 412 / 1.08.
    const string MacViewBox = "130.5 130.5 763 763";

    public static void Run(string src, string root)
    {
        XDocument mark = LoadSvg(Path.Combine(src, "mark.svg"));
        XDocument background = LoadSvg(Path.Combine(src, "background.svg"));

        // ---- Android: adaptive icon (API 26+; minSdk is 29, so no bitmap fallbacks are needed) ----
        Write(root, AndroidRes + "/drawable/ic_launcher_foreground.xml", VectorDrawable(mark, "mark.svg", monochrome: false));
        Write(root, AndroidRes + "/drawable/ic_launcher_monochrome.xml", VectorDrawable(mark, "mark.svg", monochrome: true));
        Write(root, AndroidRes + "/drawable/ic_launcher_background.xml", VectorDrawable(background, "background.svg", monochrome: false));
        string adaptive = """
            <?xml version="1.0" encoding="utf-8"?>
            <!-- Generated by scripts/gen-icons.sh from assets/icon. Do not edit. -->
            <adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
              <background android:drawable="@drawable/ic_launcher_background" />
              <foreground android:drawable="@drawable/ic_launcher_foreground" />
              <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
            </adaptive-icon>

            """;
        Write(root, AndroidRes + "/mipmap-anydpi-v26/ic_launcher.xml", adaptive);
        Write(root, AndroidRes + "/mipmap-anydpi-v26/ic_launcher_round.xml", adaptive);

        // ---- macOS app icon: Icon Composer bundle, compiled by actool at build time ----
        string icon = MacRes + "/AppIcon.icon";
        List<string> layers = LayerIds(mark);
        foreach (string id in layers)
        {
            Write(root, icon + "/Assets/" + id + ".svg", Layer(mark, id));
        }

        Write(root, icon + "/icon.json", IconJson(background, layers));

        // ---- macOS menu bar: template glyphs in an asset catalog ----
        string catalog = MacRes + "/Assets.xcassets";
        Write(root, catalog + "/Contents.json", """
            {
              "info" : {
                "author" : "xcode",
                "version" : 1
              }
            }

            """);
        string? glyph = null;
        foreach ((string state, string asset) in MenuBarStates)
        {
            string file = "menubar-" + state + ".svg";
            XDocument doc = LoadSvg(Path.Combine(src, file));
            if (doc.Descendants(Svg + "mask").Any())
            {
                throw new InvalidDataException(file + ": <mask> is rasterised at 18 px by CoreSVG (blurry on Retina); use an even-odd clip path or fill.");
            }

            XElement g = doc.Descendants(Svg + "g").SingleOrDefault(e => (string?)e.Attribute("id") == "glyph")
                ?? throw new InvalidDataException(file + ": no <g id=\"glyph\">.");
            string normalized = Regex.Replace(g.ToString(SaveOptions.DisableFormatting), @">\s+<", "><");
            if (glyph is not null && glyph != normalized)
            {
                throw new InvalidDataException(file + ": <g id=\"glyph\"> differs from menubar-idle.svg; the base glyph must be identical in every state.");
            }

            glyph = normalized;
            Write(root, catalog + "/" + asset + ".imageset/" + file, Generated(doc, file));
            Write(root, catalog + "/" + asset + ".imageset/Contents.json", $$"""
                {
                  "images" : [
                    {
                      "filename" : "{{file}}",
                      "idiom" : "universal"
                    }
                  ],
                  "info" : {
                    "author" : "xcode",
                    "version" : 1
                  },
                  "properties" : {
                    "preserves-vector-representation" : true,
                    "template-rendering-intent" : "template"
                  }
                }

                """);
        }
    }

    // ------------------------------------------------------------------ SVG helpers

    static XDocument LoadSvg(string path)
    {
        if (!File.Exists(path))
        {
            throw new InvalidDataException("missing master " + path);
        }

        XDocument doc = XDocument.Load(path, LoadOptions.PreserveWhitespace);
        if (doc.Root?.Name != Svg + "svg")
        {
            throw new InvalidDataException(path + ": not an SVG document.");
        }

        return doc;
    }

    // A copy of the master without its comments, headed by a "generated" note.
    static string Generated(XDocument master, string file)
    {
        var doc = new XDocument(master);
        foreach (XComment c in doc.Nodes().OfType<XComment>().ToList())
        {
            c.Remove();
        }

        foreach (XComment c in doc.Descendants().SelectMany(e => e.Nodes()).OfType<XComment>().ToList())
        {
            if (c.NextNode is XText ws && string.IsNullOrWhiteSpace(ws.Value))
            {
                ws.Remove();
            }

            c.Remove();
        }

        return "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
            + "<!-- Generated by scripts/gen-icons.sh from assets/icon/" + file + ". Do not edit. -->\n"
            + doc.Root!.ToString(SaveOptions.None).Replace("\r\n", "\n", StringComparison.Ordinal) + "\n";
    }

    // Top-level layers: the <g id="…"> groups of mark.svg, bottom first (SVG paint order).
    static List<string> LayerIds(XDocument mark)
    {
        var ids = mark.Root!.Descendants(Svg + "g").Select(e => (string?)e.Attribute("id")).OfType<string>().ToList();
        if (ids.Count == 0)
        {
            throw new InvalidDataException("mark.svg: no <g id=\"…\"> layer groups.");
        }

        return ids;
    }

    // mark.svg reduced to one layer group, cropped to the macOS icon square.
    static string Layer(XDocument mark, string id)
    {
        var doc = new XDocument(mark);
        foreach (XElement g in doc.Root!.Descendants(Svg + "g").Where(e => e.Attribute("id") is { } a && a.Value != id).ToList())
        {
            if (g.PreviousNode is XText ws && string.IsNullOrWhiteSpace(ws.Value))
            {
                ws.Remove();
            }

            g.Remove();
        }

        doc.Root!.SetAttributeValue("viewBox", MacViewBox);
        return Generated(doc, "mark.svg (layer \"" + id + "\")");
    }

    static string IconJson(XDocument background, List<string> layers)
    {
        List<XElement> stops = background.Descendants(Svg + "stop").ToList();
        if (stops.Count < 2)
        {
            throw new InvalidDataException("background.svg: the gradient needs at least two stops.");
        }

        // Icon Composer's linear gradient has two colours: the first and the last stop (the middle one sits on the
        // straight line between them, within a step of 8-bit rounding).
        string top = IconColor(Attr(stops[0], "stop-color"));
        string bottom = IconColor(Attr(stops[^1], "stop-color"));
        var sb = new StringBuilder();
        sb.Append("{\n");
        sb.Append("  \"fill\" : {\n");
        sb.Append("    \"linear-gradient\" : [\n");
        sb.Append("      \"").Append(top).Append("\",\n");
        sb.Append("      \"").Append(bottom).Append("\"\n");
        sb.Append("    ],\n");
        sb.Append("    \"orientation\" : {\n");
        sb.Append("      \"start\" : {\n        \"x\" : 0.5,\n        \"y\" : 0\n      },\n");
        sb.Append("      \"stop\" : {\n        \"x\" : 0.5,\n        \"y\" : 1\n      }\n");
        sb.Append("    }\n");
        sb.Append("  },\n");
        sb.Append("  \"groups\" : [\n");
        sb.Append("    {\n");
        sb.Append("      \"layers\" : [\n");
        for (int i = layers.Count - 1; i >= 0; i--) // Icon Composer lists the top layer first.
        {
            sb.Append("        {\n");
            sb.Append("          \"image-name\" : \"").Append(layers[i]).Append(".svg\",\n");
            sb.Append("          \"name\" : \"").Append(layers[i]).Append("\"\n");
            sb.Append("        }").Append(i > 0 ? ",\n" : "\n");
        }

        sb.Append("      ],\n");
        sb.Append("      \"shadow\" : {\n        \"kind\" : \"neutral\",\n        \"opacity\" : 0.5\n      },\n");
        // Opaque layers: the system still adds its glass edges and highlights, but the colours stay the ones the
        // Android icon shows (consistent across systems).
        sb.Append("      \"translucency\" : {\n        \"enabled\" : false,\n        \"value\" : 0\n      }\n");
        sb.Append("    }\n");
        sb.Append("  ],\n");
        sb.Append("  \"supported-platforms\" : {\n    \"squares\" : [\n      \"macOS\"\n    ]\n  }\n");
        sb.Append("}\n");
        return sb.ToString();
    }

    static string IconColor(string hex)
    {
        (int r, int g, int b) = Rgb(hex);
        return string.Create(CultureInfo.InvariantCulture, $"srgb:{r / 255.0:0.00000},{g / 255.0:0.00000},{b / 255.0:0.00000},1.00000");
    }

    // ------------------------------------------------------------------ SVG -> Android VectorDrawable

    sealed record Style(string? Fill, string? Stroke, string? StrokeWidth, string? LineCap, string? LineJoin);

    static readonly HashSet<string> AllowedAttributes =
    [
        "id", "d", "x", "y", "width", "height", "rx", "cx", "cy", "r", "transform",
        "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin",
    ];

    static string VectorDrawable(XDocument doc, string file, bool monochrome)
    {
        XElement svg = doc.Root!;
        double[] vb = Numbers(Attr(svg, "viewBox"));
        if (vb.Length != 4 || vb[0] != 0 || vb[1] != 0)
        {
            throw new InvalidDataException(file + ": viewBox must be \"0 0 w h\".");
        }

        Dictionary<string, XElement> gradients = svg.Descendants(Svg + "linearGradient")
            .ToDictionary(e => Attr(e, "id"), e => e, StringComparer.Ordinal);

        XNamespace a = AndroidNs;
        XNamespace aapt = AaptNs;
        var vector = new XElement("vector",
            new XAttribute(XNamespace.Xmlns + "android", AndroidNs),
            new XAttribute(XNamespace.Xmlns + "aapt", AaptNs),
            new XAttribute(a + "width", "108dp"),
            new XAttribute(a + "height", "108dp"),
            new XAttribute(a + "viewportWidth", Num(vb[2])),
            new XAttribute(a + "viewportHeight", Num(vb[3])));

        var ctx = new VdContext(file, monochrome, gradients, a, aapt);
        foreach (XElement child in svg.Elements())
        {
            Convert(ctx, child, new Style("#000000", null, "1", null, null), vector);
        }

        if (!gradients.Values.Any(_ => true))
        {
            vector.Attribute(XNamespace.Xmlns + "aapt")!.Remove();
        }

        string note = monochrome
            ? "Themed-icon layer: only its alpha is used; the launcher tints it."
            : "Adaptive-icon layer: 1024 viewport units = 108 dp.";
        return "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
            + "<!-- Generated by scripts/gen-icons.sh from assets/icon/" + file + ". Do not edit. " + note + " -->\n"
            + vector.ToString(SaveOptions.None).Replace("\r\n", "\n", StringComparison.Ordinal) + "\n";
    }

    sealed record VdContext(string File, bool Monochrome, Dictionary<string, XElement> Gradients, XNamespace A, XNamespace Aapt);

    static void Convert(VdContext ctx, XElement e, Style inherited, XElement parent)
    {
        string name = e.Name.LocalName;
        if (e.Name.Namespace != Svg)
        {
            throw new InvalidDataException(ctx.File + ": unsupported element " + e.Name + ".");
        }

        if (name is "defs" or "linearGradient" or "stop")
        {
            return; // Gradients are resolved where a fill references them.
        }

        foreach (XAttribute attr in e.Attributes())
        {
            if (!attr.IsNamespaceDeclaration && !AllowedAttributes.Contains(attr.Name.LocalName))
            {
                throw new InvalidDataException($"{ctx.File}: <{name}> attribute '{attr.Name.LocalName}' is outside the VectorDrawable subset.");
            }
        }

        var style = new Style(
            (string?)e.Attribute("fill") ?? inherited.Fill,
            (string?)e.Attribute("stroke") ?? inherited.Stroke,
            (string?)e.Attribute("stroke-width") ?? inherited.StrokeWidth,
            (string?)e.Attribute("stroke-linecap") ?? inherited.LineCap,
            (string?)e.Attribute("stroke-linejoin") ?? inherited.LineJoin);

        XNamespace a = ctx.A;
        switch (name)
        {
            case "g":
            {
                XElement target = parent;
                if (e.Attribute("transform") is { } t)
                {
                    (double sx, double sy, double tx, double ty) = Transform(ctx.File, t.Value);
                    target = new XElement("group");
                    if (sx != 1) target.Add(new XAttribute(a + "scaleX", Num(sx)));
                    if (sy != 1) target.Add(new XAttribute(a + "scaleY", Num(sy)));
                    if (tx != 0) target.Add(new XAttribute(a + "translateX", Num(tx)));
                    if (ty != 0) target.Add(new XAttribute(a + "translateY", Num(ty)));
                    parent.Add(target);
                }
                else if ((string?)e.Attribute("id") is { } id)
                {
                    target = new XElement("group", new XAttribute(a + "name", id));
                    parent.Add(target);
                }

                foreach (XElement child in e.Elements())
                {
                    Convert(ctx, child, style, target);
                }

                return;
            }

            case "path":
                parent.Add(PathElement(ctx, Attr(e, "d"), style));
                return;

            case "rect":
            {
                double x = Double(e, "x", 0), y = Double(e, "y", 0), w = Double(e, "width"), h = Double(e, "height"), r = Double(e, "rx", 0);
                string d = r == 0
                    ? $"M{Num(x)} {Num(y)}H{Num(x + w)}V{Num(y + h)}H{Num(x)}Z"
                    : $"M{Num(x + r)} {Num(y)}H{Num(x + w - r)}A{Num(r)} {Num(r)} 0 0 1 {Num(x + w)} {Num(y + r)}"
                      + $"V{Num(y + h - r)}A{Num(r)} {Num(r)} 0 0 1 {Num(x + w - r)} {Num(y + h)}"
                      + $"H{Num(x + r)}A{Num(r)} {Num(r)} 0 0 1 {Num(x)} {Num(y + h - r)}"
                      + $"V{Num(y + r)}A{Num(r)} {Num(r)} 0 0 1 {Num(x + r)} {Num(y)}Z";
                parent.Add(PathElement(ctx, d, style));
                return;
            }

            case "circle":
            {
                double cx = Double(e, "cx"), cy = Double(e, "cy"), r = Double(e, "r");
                string d = $"M{Num(cx - r)} {Num(cy)}A{Num(r)} {Num(r)} 0 1 0 {Num(cx + r)} {Num(cy)}A{Num(r)} {Num(r)} 0 1 0 {Num(cx - r)} {Num(cy)}Z";
                parent.Add(PathElement(ctx, d, style));
                return;
            }

            default:
                throw new InvalidDataException($"{ctx.File}: <{name}> is outside the VectorDrawable subset (g, path, rect, circle, linearGradient).");
        }
    }

    static XElement PathElement(VdContext ctx, string d, Style s)
    {
        XNamespace a = ctx.A;
        var p = new XElement("path", new XAttribute(a + "pathData", d));
        if (s.Fill is { } fill && fill != "none")
        {
            Match m = Regex.Match(fill, @"^url\(#([^)]+)\)$");
            if (m.Success && !ctx.Monochrome)
            {
                p.Add(new XElement(ctx.Aapt + "attr", new XAttribute("name", "android:fillColor"), Gradient(ctx, m.Groups[1].Value)));
            }
            else
            {
                p.Add(new XAttribute(a + "fillColor", VdColor(ctx, m.Success ? "#000000" : fill)));
            }
        }

        if (s.Stroke is { } stroke && stroke != "none")
        {
            p.Add(new XAttribute(a + "strokeColor", VdColor(ctx, stroke)));
            p.Add(new XAttribute(a + "strokeWidth", s.StrokeWidth ?? "1"));
            if (s.LineCap is { } cap && cap != "butt") p.Add(new XAttribute(a + "strokeLineCap", cap));
            if (s.LineJoin is { } join && join != "miter") p.Add(new XAttribute(a + "strokeLineJoin", join));
        }

        return p;
    }

    static XElement Gradient(VdContext ctx, string id)
    {
        if (!ctx.Gradients.TryGetValue(id, out XElement? g) || (string?)g.Attribute("gradientUnits") != "userSpaceOnUse")
        {
            throw new InvalidDataException($"{ctx.File}: fill url(#{id}) must name a userSpaceOnUse linearGradient.");
        }

        XNamespace a = ctx.A;
        var vd = new XElement("gradient",
            new XAttribute(a + "type", "linear"),
            new XAttribute(a + "startX", Num(Double(g, "x1"))),
            new XAttribute(a + "startY", Num(Double(g, "y1"))),
            new XAttribute(a + "endX", Num(Double(g, "x2"))),
            new XAttribute(a + "endY", Num(Double(g, "y2"))));
        foreach (XElement stop in g.Elements(Svg + "stop"))
        {
            vd.Add(new XElement("item",
                new XAttribute(a + "offset", Num(Double(stop, "offset"))),
                new XAttribute(a + "color", VdColor(ctx, Attr(stop, "stop-color")))));
        }

        return vd;
    }

    static string VdColor(VdContext ctx, string hex)
    {
        if (ctx.Monochrome)
        {
            return "#FFFFFFFF";
        }

        (int r, int g, int b) = Rgb(hex);
        return string.Create(CultureInfo.InvariantCulture, $"#FF{r:X2}{g:X2}{b:X2}");
    }

    // translate(...)/scale(...) lists only (no rotation or skew: a VectorDrawable group can't express a general
    // matrix with pivot 0 any other way). Returns x' = sx * x + tx.
    static (double Sx, double Sy, double Tx, double Ty) Transform(string file, string value)
    {
        double sx = 1, sy = 1, tx = 0, ty = 0;
        foreach (Match m in Regex.Matches(value, @"(\w+)\(([^)]*)\)"))
        {
            double[] n = Numbers(m.Groups[2].Value);
            switch (m.Groups[1].Value)
            {
                case "translate" when n.Length is 1 or 2:
                    tx += sx * n[0];
                    ty += sy * (n.Length == 2 ? n[1] : 0);
                    break;
                case "scale" when n.Length is 1 or 2:
                    sx *= n[0];
                    sy *= n.Length == 2 ? n[1] : n[0];
                    break;
                default:
                    throw new InvalidDataException($"{file}: transform '{m.Value}' is outside the subset (translate, scale).");
            }
        }

        return (sx, sy, tx, ty);
    }

    // ------------------------------------------------------------------ small parsers

    static string Attr(XElement e, string name) =>
        (string?)e.Attribute(name) ?? throw new InvalidDataException($"<{e.Name.LocalName}> needs '{name}'.");

    static double Double(XElement e, string name, double? fallback = null)
    {
        string? v = (string?)e.Attribute(name);
        if (v is null)
        {
            return fallback ?? throw new InvalidDataException($"<{e.Name.LocalName}> needs '{name}'.");
        }

        return double.Parse(v, NumberStyles.Float, CultureInfo.InvariantCulture);
    }

    static double[] Numbers(string s) =>
        s.Split([' ', ','], StringSplitOptions.RemoveEmptyEntries).Select(x => double.Parse(x, NumberStyles.Float, CultureInfo.InvariantCulture)).ToArray();

    static string Num(double v) => Math.Round(v, 4).ToString("0.####", CultureInfo.InvariantCulture);

    static (int R, int G, int B) Rgb(string hex)
    {
        Match m = Regex.Match(hex, "^#([0-9A-Fa-f]{6})$");
        if (!m.Success)
        {
            throw new InvalidDataException($"colour '{hex}' must be #RRGGBB.");
        }

        int v = int.Parse(m.Groups[1].Value, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
        return ((v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF);
    }

    static void Write(string root, string relative, string content)
    {
        string path = Path.Combine(root, relative);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        Console.WriteLine("  wrote " + relative);
    }
}
